"""Regimes and episodes.

A *regime* is a contiguous stretch of a normal training stream that the
sampler believes was generated by one stationary process.  A *task* in
the meta-learning sense is one regime.  An *episode* drawn from a regime
is a (support, query) pair of windows.

Three ways of cutting a stream into regimes are provided so that the
drift-aware sampler (Module 1 of DAMAD) can be ablated:

  drift   boundaries placed by ADWIN on a scalar summary of the stream
  chunk   fixed-length contiguous chunks (no drift awareness)
  random  no boundaries at all; windows drawn from anywhere in the stream
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import List, Sequence

import numpy as np

from .windows import sample_windows
from ..online.adwin import ADWIN


@dataclass
class Regime:
    entity: str
    X: np.ndarray            # (T, d) standardised normal data
    start: int               # offset of this regime in its source stream

    def __len__(self) -> int:
        return len(self.X)


def segment_drift(X: np.ndarray, entity: str, min_len: int, delta: float = 1e-3,
                  block: int = 10, vote_frac: float = 0.2, horizon: int = 200) -> List[Regime]:
    """ADWIN-based segmentation of one stream into regimes.

    One ADWIN runs per sensor on block means; a boundary is placed when
    at least `vote_frac` of the sensors have reported a change inside
    the last `horizon` steps.  Over-segmentation only costs episode
    diversity here, so the vote is deliberately permissive."""
    T, d = X.shape
    n = (T // block) * block
    Xb = X[:n].reshape(-1, block, d).mean(1)
    dets = [ADWIN(delta=delta, clock=1, min_window=5) for _ in range(d)]
    hb = max(1, horizon // block)
    recent = np.zeros((len(Xb), d), dtype=bool)
    cuts = [0]
    for i, row in enumerate(Xb):
        for j in range(d):
            recent[i, j] = dets[j].update(float(row[j]))
        lo = max(0, i - hb + 1)
        t = i * block
        if recent[lo:i + 1].any(0).mean() >= vote_frac and t - cuts[-1] >= min_len:
            cuts.append(t)
    cuts.append(T)
    regs = []
    for a, b in zip(cuts[:-1], cuts[1:]):
        if b - a >= min_len:
            regs.append(Regime(entity, X[a:b], a))
    if not regs:                       # stream shorter than min_len: keep it whole
        regs.append(Regime(entity, X, 0))
    return regs


def segment_chunks(X: np.ndarray, entity: str, chunk: int, min_len: int) -> List[Regime]:
    regs = []
    for a in range(0, len(X), chunk):
        b = min(a + chunk, len(X))
        if b - a >= min_len:
            regs.append(Regime(entity, X[a:b], a))
    if not regs:
        regs.append(Regime(entity, X, 0))
    return regs


def build_regimes(entities: Sequence, sampler: str, W: int, min_len: int = 400,
                  chunk: int = 2000) -> List[Regime]:
    regs: List[Regime] = []
    for e in entities:
        streams = getattr(e, "train_segments", None) or [e.X_train]
        for j, X in enumerate(streams):
            name = f"{e.dataset}/{e.name}#{j}"
            if sampler == "drift":
                regs.extend(segment_drift(X, name, min_len=max(min_len, 4 * W)))
            elif sampler == "chunk":
                regs.extend(segment_chunks(X, name, chunk=chunk, min_len=max(min_len, 4 * W)))
            elif sampler == "random":
                regs.append(Regime(name, X, 0))
            else:
                raise ValueError(sampler)
    return regs


def sample_episode(regime: Regime, W: int, k_shot: int, n_query: int, rng: np.random.Generator):
    """Support and query windows from one regime.  Support windows are
    drawn from the first part of the regime and query from the rest when
    the regime is long enough, so that the inner loop cannot peek at the
    query steps."""
    T = len(regime)
    if T >= 4 * W + k_shot + n_query:
        cut = T // 2
        S = sample_windows(regime.X[:cut], W, k_shot, rng)
        Q = sample_windows(regime.X[cut:], W, n_query, rng)
    else:
        S = sample_windows(regime.X, W, k_shot, rng)
        Q = sample_windows(regime.X, W, n_query, rng)
    return S, Q
